import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { execSync } from "node:child_process";
import { resolveFrpPublicUrl } from "./resolve-frp-url.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

function localLanIp() {
  try {
    return execSync("hostname -I | awk '{print $1}'", { encoding: "utf8" }).trim();
  } catch {
    return "127.0.0.1";
  }
}

function loadPublicBaseUrl() {
  try {
    return resolveFrpPublicUrl();
  } catch {
    const metaPath = path.join(ROOT, "config/public-endpoint.json");
    if (!fs.existsSync(metaPath)) throw new Error("未找到 frpc.toml 且无 config/public-endpoint.json");
    const meta = JSON.parse(fs.readFileSync(metaPath, "utf8"));
    return {
      frpcPath: meta.frpcPath ?? "(cached)",
      publicBaseUrl: meta.publicBaseUrl,
      serverAddr: meta.serverAddr,
      remotePort: meta.remotePort,
      proxyName: meta.proxyName,
    };
  }
}
const frp = loadPublicBaseUrl();
const lanIp = localLanIp();
const publicBase = frp.publicBaseUrl.replace(/\/$/, "");
const lanBase = `http://${lanIp}`;
const apiBaseUrl = `${publicBase}/api/v1`;
const wsUrl = publicBase.replace(/^http/, "ws") + "/ws";
const now = new Date().toISOString();

const appConfig = {
  apiBaseUrl,
  wsUrl,
  features: {
    enableAI: true,
    enablePrintService: true,
    maxUploadSizeMB: 200,
    enableCommunity: true,
  },
  version: now,
  appVersion: "0.0.3",
  maintenance: false,
  publicBaseUrl: publicBase,
  lanBaseUrl: lanBase,
};

const configUrls = [
  `${publicBase}/app-config.json`,
  `${lanBase}/app-config.json`,
];

const bootstrapDart = `// GENERATED by scripts/sync-public-config.mjs — do not edit manually
class BootstrapConfig {
  BootstrapConfig._();

  static const publicBaseUrl = '${publicBase}';
  static const appVersion = '0.0.3';
  static const configUrls = <String>[
${configUrls.map((u) => `    '${u}',`).join("\n")}
  ];
}
`;

const endpointMeta = {
  generatedAt: now,
  frpcPath: frp.frpcPath,
  publicBaseUrl: publicBase,
  lanBaseUrl: lanBase,
  serverAddr: frp.serverAddr,
  remotePort: frp.remotePort,
  proxyName: frp.proxyName,
};

fs.mkdirSync(path.join(ROOT, "config-server/public"), { recursive: true });
fs.mkdirSync(path.join(ROOT, "config"), { recursive: true });
fs.mkdirSync(path.join(ROOT, "mobile-app/lib/config"), { recursive: true });

fs.writeFileSync(path.join(ROOT, "config-server/public/app-config.json"), JSON.stringify(appConfig, null, 2) + "\n");
fs.writeFileSync(path.join(ROOT, "config/public-endpoint.json"), JSON.stringify(endpointMeta, null, 2) + "\n");
fs.writeFileSync(path.join(ROOT, "mobile-app/lib/config/bootstrap_config.dart"), bootstrapDart);

try {
  execSync("node scripts/sync-apk-download.mjs", { cwd: ROOT, stdio: "inherit" });
} catch {
  console.warn("APK 同步跳过（可稍后运行 node scripts/sync-apk-download.mjs）");
}

console.log("已同步公网配置:");
console.log("  FRP:", frp.frpcPath);
console.log("  公网:", publicBase);
console.log("  局域网:", lanBase);
console.log("  API:", apiBaseUrl);
